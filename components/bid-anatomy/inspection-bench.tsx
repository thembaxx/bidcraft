"use client";

import { useId, useRef, type KeyboardEvent } from "react";
import { motion, useInView, useReducedMotion } from "motion/react";
import { INSPECTION_LABELS, type InspectionState } from "@/lib/bid-anatomy";
import type { TenderClause } from "@/lib/types";
import art from "./bench-art.json";

interface InspectionBenchProps {
  stations: { clause: TenderClause; state: InspectionState }[];
  selectedId: string;
  onSelect: (id: string) => void;
  progress: number;
  theme: "light" | "dark";
}

export function InspectionBench({
  stations,
  selectedId,
  onSelect,
  progress,
  theme,
}: InspectionBenchProps) {
  const uid = useId().replace(/:/g, "");
  const root = useRef<HTMLElement>(null);
  const inView = useInView(root, { margin: "40px" });
  const reducedMotion = useReducedMotion();
  const transition =
    reducedMotion || !inView
      ? { duration: 0 }
      : { type: "spring" as const, stiffness: 90, damping: 21 };
  const stationIndex = (piece: string) =>
    piece.startsWith("station-") ? Number(piece.slice(8)) : -1;
  const keySelect = (event: KeyboardEvent<SVGGElement>, index: number) => {
    let target = index;
    if (event.key === "ArrowRight" || event.key === "ArrowDown")
      target = (index + 1) % stations.length;
    else if (event.key === "ArrowLeft" || event.key === "ArrowUp")
      target = (index - 1 + stations.length) % stations.length;
    else if (event.key === "Home") target = 0;
    else if (event.key === "End") target = stations.length - 1;
    else if (event.key === "Enter" || event.key === " ") {
      event.preventDefault();
      onSelect(stations[index].clause.id);
      return;
    } else return;
    event.preventDefault();
    onSelect(stations[target].clause.id);
    document.getElementById(`${uid}-pin-${target}`)?.focus();
  };

  return (
    <figure
      ref={root}
      className="bid-bench iso"
      data-theme={theme}
      aria-labelledby={`${uid}-caption`}
    >
      <div className="bench-frame iso-plate">
        <div className="bench-corners">
          <span>Fig. 01 / Bid inspection</span>
          <span>{stations.length} active stations</span>
        </div>
        <svg
          className="iso-svg"
          viewBox={`0 0 ${art.width} ${art.height}`}
          role="group"
          aria-label="Interactive bid inspection bench"
          aria-describedby={`${uid}-hint`}
        >
          <defs>
            {art.items
              .filter((item) => "clip" in item)
              .map((item) => (
                <clipPath key={item.name} id={`${uid}-${item.name}`}>
                  <path d={(item as { clip: string }).clip} />
                </clipPath>
              ))}
          </defs>
          <path className="iso-halo" d={art.halo} />
          {art.items.map((item) => {
            const index = stationIndex(item.piece);
            const station = index >= 0 ? stations[index] : undefined;
            const approved = station?.state === "approved";
            // All markup is checked-in geometry generated by Anatomy; tender text never enters SVG markup.
            const solid = <g dangerouslySetInnerHTML={{ __html: item.svg }} />;
            return (
              <g
                key={item.name}
                data-part={item.name}
                data-station={index >= 0 ? index : undefined}
                data-selected={station?.clause.id === selectedId ? "" : undefined}
                data-unused={index >= 0 && !station ? "" : undefined}
              >
                {"clip" in item ? (
                  <g clipPath={`url(#${uid}-${item.name})`}>
                    <motion.g
                      initial={false}
                      animate={{ x: approved ? art.motion[0] : 0, y: approved ? art.motion[1] : 0 }}
                      transition={transition}
                    >
                      {solid}
                    </motion.g>
                  </g>
                ) : item.moving ? (
                  <motion.g
                    initial={false}
                    animate={{ x: approved ? art.motion[0] : 0, y: approved ? art.motion[1] : 0 }}
                    transition={transition}
                  >
                    {solid}
                  </motion.g>
                ) : (
                  solid
                )}
              </g>
            );
          })}
          <g transform={art.gaugeMatrix} aria-hidden="true">
            <motion.g
              initial={false}
              animate={{ rotate: -125 + Math.max(0, Math.min(1, progress)) * 250 }}
              transition={transition}
            >
              <path
                className="iso-line"
                data-tone="lit"
                data-free=""
                d="M0 2 L0 -11"
                strokeWidth="1.3"
              />
            </motion.g>
            <circle r="1.5" className="bench-gauge-hub" />
          </g>
          {stations.map(({ clause, state }, index) => {
            const [x, y] = art.pins[index];
            return (
              <g
                key={clause.id}
                id={`${uid}-pin-${index}`}
                role="button"
                tabIndex={clause.id === selectedId ? 0 : -1}
                aria-label={`Inspect ${clause.code}: ${INSPECTION_LABELS[state]}`}
                aria-pressed={clause.id === selectedId}
                onClick={() => onSelect(clause.id)}
                onKeyDown={(event) => keySelect(event, index)}
                className="bench-pin-target"
                data-status={state}
              >
                <motion.g
                  initial={false}
                  animate={{
                    x: state === "approved" ? art.motion[0] : 0,
                    y: state === "approved" ? art.motion[1] : 0,
                  }}
                  transition={transition}
                >
                  <circle cx={x} cy={y} r="24" className="bench-hit" />
                  <circle cx={x} cy={y - 1} r="3" className="bench-lamp" />
                  <circle cx={x} cy={y - 1} r="11" className="bench-focus-ring" />
                </motion.g>
              </g>
            );
          })}
        </svg>
        <div className="bench-bottom" id={`${uid}-hint`}>
          <span>Select a pin to inspect its requirement.</span>
          <span>↓ reviewed · ↑ review needed</span>
        </div>
      </div>
      <figcaption id={`${uid}-caption`} className="bench-caption">
        Pins retract after a recorded human approval. The gauge shows reviewed mandatory
        requirements. This is a review aid; confirm eligibility before submission.
      </figcaption>
    </figure>
  );
}
